#!/usr/bin/env python3
"""Generate logging no-op stubs for SDK functions from the repo's own headers.

usage: gen_stubs.py <repo> <symbols.txt> <already_defined_src...> > stubs.c
Symbols already defined in the given hand-written sources are skipped.
"""
import re, sys, glob, os

repo, symfile, *impl = sys.argv[1:]
want = [l.strip() for l in open(symfile) if l.strip()]

def strip_comments(t):
    t = re.sub(r'/\*.*?\*/', ' ', t, flags=re.S)
    t = re.sub(r'//[^\n]*', ' ', t)
    return re.sub(r'^[ \t]*#[^\n]*(\\\n[^\n]*)*', ' ', t, flags=re.M)

defined = set()
for f in impl:
    for m in re.finditer(r'^[A-Za-z_][\w\s\*]*?\b(\w+)\s*\([^;{]*\)\s*\{', open(f).read(), re.M):
        defined.add(m.group(1))

for f in impl:
    for m in re.finditer(r'^[A-Za-z_][\w\s\*]*?\b(\w+)\s*(\[[^\]]*\])?\s*=', open(f).read(), re.M):
        defined.add(m.group(1))
    for m in re.finditer(r'^[A-Za-z_][\w\s\*]*?\b(\w+)\s*;', open(f).read(), re.M):
        defined.add(m.group(1))

hdrs = glob.glob(os.path.join(repo, 'include', '**', '*.h'), recursive=True) + \
       glob.glob(os.path.join(repo, 'extern', 'musyx', 'include', '**', '*.h'), recursive=True)
texts = {h: strip_comments(open(h, errors='ignore').read()) for h in hdrs}

def split_args(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == '(': depth += 1
        if ch == ')': depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip()); cur = ''
        else:
            cur += ch
    if cur.strip(): out.append(cur.strip())
    return out

QUAL = {'const', 'struct', 'enum', 'volatile', 'unsigned', 'signed', 'long', 'short', 'register'}

def fix_arg(a, i):
    a = re.sub(r'\bregister\b', '', a).strip()
    if a in ('void', '...'): return a
    if '(*)' in a: return a.replace('(*)', '(*a%d)' % i)
    if '(' in a: return a  # named function pointer
    toks = [t for t in re.split(r'[\s\*\[\]\d]+', a) if t and t not in QUAL]
    if len(toks) >= 2: return a
    return a + ' a%d' % i

def find_proto(name):
    pat = re.compile(r'(?<![\w])' + re.escape(name) + r'\s*\(')
    for h, t in texts.items():
        for m in pat.finditer(t):
            start = max(t.rfind(';', 0, m.start()), t.rfind('}', 0, m.start()), t.rfind('{', 0, m.start())) + 1
            ret = ' '.join(t[start:m.start()].split())
            ret = re.sub(r'\b(extern|static|inline|__inline__|MWERKS_FP)\b', '', ret).replace('"C"', '').strip()
            depth, j = 1, m.end()
            while j < len(t) and depth:
                depth += (t[j] == '(') - (t[j] == ')'); j += 1
            args = t[m.end():j - 1]
            rest = t[j:].lstrip()
            if not rest.startswith(';') or not ret or ret.startswith('return') or '=' in ret:
                continue
            return ret, args
    return None

print('/* GENERATED by tools/gen_stubs.py - do not edit. Logging no-op stubs. */')
print('#include <dolphin.h>\n#include <string.h>\n#include "port_log.h"')
for h in sorted(glob.glob(os.path.join(repo,'include','msm','*.h'))):
    print('#include "msm/%s"' % os.path.basename(h))
print()
missing = []
for n in want:
    if n in defined: continue
    p = find_proto(n)
    if not p: missing.append(n); continue
    ret, args = p
    al = split_args(args)
    if '...' in al: missing.append(n + ' (varargs)'); continue
    argstr = ', '.join(fix_arg(a, i) for i, a in enumerate(al)) or 'void'
    body = 'PORT_STUB("%s");' % n
    if ret != 'void':
        body += ' %s r; memset(&r, 0, sizeof(r)); return r;' % ret
    print('%s %s(%s) { %s }' % (ret, n, argstr, body))
if missing:
    sys.stderr.write('no prototype found for: ' + ' '.join(missing) + '\n')
